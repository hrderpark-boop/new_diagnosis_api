# 통합 뷰: {key: {"situation": [...], "question": [...]}}. 분석·게이트는 여전히
# SUBCOMPETENCY_ANCHORS(situation 리스트)를 그대로 읽는다(호환층 — 무변경).
SUBCOMPETENCY_ANCHOR_SETS = {
    k: {"situation": list(v), "question": list(SUBCOMPETENCY_ANCHOR_QUESTIONS.get(k, []))}
    for k, v in SUBCOMPETENCY_ANCHORS.items()
}


def get_anchor_questions(sub_key: str) -> list[str]:
    """하위역량 키 → 대상자에게 던지는 앵커 질문 2개(없으면 빈 리스트)."""
    return list(SUBCOMPETENCY_ANCHOR_QUESTIONS.get(sub_key, []))


def find_sub_key_by_name(chapter_key: str, sub_name: str) -> str | None:
    """챕터 안에서 하위역량 '이름'(원장·state 는 이름을 쓴다) → indicator 키."""
    fw = COMPETENCY_FRAMEWORK.get(chapter_key, {})
    for k, v in (fw.get("indicators") or {}).items():
        if v.get("name") == sub_name:
            return k
    return None
